        State.Success(
            manga = mangaAndChapters.manga,
            source = mangaAndChapters.source,
            sourceName = mangaAndChapters.sourceName,
            chapters = mangaAndChapters.chapters.map { item ->
                if (item.id in selectedIds) item.copy(selected = true) else item
